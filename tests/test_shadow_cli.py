def test_the_runbook_documents_every_cli_action():
    """A runbook whose commands do not run is worse than none: it is trusted."""
    from pathlib import Path

    repo = Path(__file__).resolve().parents[1]
    runbook = repo / "docs" / "SHADOW_COMPARISON_RUNBOOK.md"
    assert runbook.exists(), "the runbook is part of the deliverable"

    text = runbook.read_text(encoding="utf-8")
    for action in ("report", "events", "acceptances", "compare", "signoff",
                   "reject", "revoke", "accept", "check", "intents", "attest"):
        assert f"ats shadow {action}" in text, f"{action} is undocumented"


def test_the_runbook_names_the_commands_that_must_not_be_taken():
    """The prohibitions are the part an operator most needs stated."""
    from pathlib import Path

    repo = Path(__file__).resolve().parents[1]
    text = (repo / "docs" / "SHADOW_COMPARISON_RUNBOOK.md").read_text(
        encoding="utf-8")
    assert "not-applicable" in text or "不适用" in text
    assert "redirect" in text.lower() or "改道" in text
