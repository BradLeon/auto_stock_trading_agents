def test_shadow_is_its_own_command_not_a_workflow_action(capsys):
    """Different artefacts with different rules.

    One command whose actions span both makes the read-only ones look as if they
    can also mutate.
    """
    with pytest.raises(SystemExit):
        cli.main(["shadow", "--help"])


def test_an_unknown_report_id_is_reported_not_silently_empty(capsys, store):
    """"no events" and "no such report" are different answers to one question."""
    code, payload = _run(capsys, ["shadow", "report", "--report-id", "typo",
                                  "--db", str(store)])
    assert code == 1
    assert "typo" in payload["error"]


def test_a_missing_required_flag_is_an_error(capsys, store):
    with pytest.raises(SystemExit):
        cli.main(["shadow", "events", "--db", str(store)])


def test_malformed_json_is_reported_as_such(capsys, store):
    with pytest.raises(SystemExit):
        cli.main(["shadow", "compare", "--report-id", "r", "--left-json", "{oops",
                  "--db", str(store)])


