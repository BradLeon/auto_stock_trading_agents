def test_check_exits_non_zero_when_the_report_is_not_citable(capsys, store):
    """So a runbook script cannot pass on a citation it just proved invalid."""
    _run(capsys, [
        "shadow", "compare", "--report-id", "rep-1", "--run-id", "r1",
        "--consumer-id", "trader", "--batch-class", "trading",
        "--scope-json", '{"p": ["x"]}', "--packet-hash", "p1",
        "--expected-triggers-json", '["t1"]',
        "--left-json", json.dumps(_CLEAN_LEFT),
        "--right-json", json.dumps(_RISK_DIVERGED_RIGHT),
        "--db", str(store)])

    code, payload = _run(capsys, ["shadow", "check", "--report-id", "rep-1",
                                  "--scope-json", '{"p": ["x"]}',
                                  "--db", str(store)])
    assert code == 1
    assert payload["citable"] is False
    assert any(sc.RISK_VERDICT in problem for problem in payload["problems"])


