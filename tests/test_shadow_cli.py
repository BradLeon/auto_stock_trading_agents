"""CLI entry points and the runbook (Phase F 3.8).

The requirement is that a report "can be regenerated by command and agrees with
the append-only record". So the assertions here are about agreement, not about
output shape: a CLI that renders a slightly different conclusion from the stored
record would be worse than no CLI, because an operator would trust the fresh-looking
one.
"""

import json

import pytest

from ats.workflow import shadow_compare as sc
from ats.workflow import shadow_ledger as sl
from ats.workflow import shadow_reports as sr
from ats.runtime import cli


@pytest.fixture
def store(tmp_path):
    return tmp_path / "reports.sqlite"


def _run(capsys, argv):
    code = cli.main(argv)
    out = capsys.readouterr().out
    return code, json.loads(out) if out.strip() else {}


_CLEAN_LEFT = {
    "_packet": {"doc": 1},
    "schedule_omission": ["t1"],
    "analyst_output": ["a"],
    "risk_verdict": {"verdict": "pass"},
    "approval_chain": {"verdict": "approved", "round_no": 1},
    "trade_attribution": {"o1": "chained"},
}
_RISK_DIVERGED_RIGHT = dict(
    _CLEAN_LEFT, risk_verdict={"verdict": "reject"})


