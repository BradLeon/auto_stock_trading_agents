def test_compare_records_and_prints_the_same_verdicts(capsys, store):
    code, payload = _run(capsys, [
        "shadow", "compare", "--report-id", "rep-1", "--run-id", "r1",
        "--consumer-id", "trader", "--batch-class", "trading",
        "--scope-json", '{"p": ["x"]}', "--packet-hash", "p1",
        "--expected-triggers-json", '["t1"]',
        "--left-json", json.dumps(_CLEAN_LEFT),
        "--right-json", json.dumps(_CLEAN_LEFT),
        "--db", str(store)])
    assert code == 0

    stored = sr.read_state("rep-1", path=store)
    # `surfaces` is a verdict map, so the comparison is against it directly.
    assert payload["verdicts"] == stored.surfaces
    assert {row["surface"] for row in payload["surfaces"]} == set(sc.SIX_SURFACES)


def test_the_report_action_reproduces_the_stored_state(capsys, store):
    _run(capsys, [
        "shadow", "compare", "--report-id", "rep-1", "--run-id", "r1",
        "--consumer-id", "trader", "--batch-class", "trading",
        "--scope-json", '{"p": ["x"]}', "--packet-hash", "p1",
        "--expected-triggers-json", '["t1"]',
        "--left-json", json.dumps(_CLEAN_LEFT),
        "--right-json", json.dumps(_CLEAN_LEFT),
        "--db", str(store)])
    _, payload = _run(capsys, ["shadow", "report", "--report-id", "rep-1",
                               "--db", str(store)])

    assert payload["surfaces"] == sr.read_state("rep-1", path=store).surfaces
    assert payload["scope_hash"] == sr.read_state("rep-1", path=store).scope_hash


