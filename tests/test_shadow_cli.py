def test_a_rejection_through_the_cli_flips_the_status(capsys, store):
    _run(capsys, [
        "shadow", "compare", "--report-id", "rep-1", "--run-id", "r1",
        "--consumer-id", "trader", "--batch-class", "trading",
        "--scope-json", '{"p": ["x"]}', "--packet-hash", "p1",
        "--expected-triggers-json", '["t1"]',
        "--left-json", json.dumps(_CLEAN_LEFT),
        "--right-json", json.dumps(_CLEAN_LEFT),
        "--db", str(store)])
    _, payload = _run(capsys, ["shadow", "reject", "--report-id", "rep-1",
                               "--actor", "reviewer", "--reason", "not good",
                               "--db", str(store)])
    assert payload["status"] == sr.REJECTED
    # The comparison is still there.
    assert len(sr.events("rep-1", path=store)) == 2


def test_accepting_a_divergence_through_the_cli(capsys, store):
    left = dict(_CLEAN_LEFT, analyst_output=[f"p-{i}" for i in range(20)])
    right = dict(left, analyst_output=[f"other-{i}" for i in range(20)])
    _run(capsys, [
        "shadow", "compare", "--report-id", "rep-1", "--run-id", "r1",
        "--consumer-id", "chief", "--batch-class", "decision",
        "--scope-json", '{"p": ["x"]}', "--packet-hash", "p1",
        "--expected-triggers-json", '["t1"]',
        "--left-json", json.dumps(left), "--right-json", json.dumps(right),
        "--db", str(store)])

    _, payload = _run(capsys, [
        "shadow", "accept", "--report-id", "rep-1", "--surface", sc.ANALYST_OUTPUT,
        "--actor", "owner", "--authority", "chief_owner",
        "--reason", "role rewrite verified", "--db", str(store)])
    assert payload["surface"] == sc.ANALYST_OUTPUT
    assert sr.read_state("rep-1", path=store).unaccepted == ()


def test_acceptances_can_be_listed(capsys, store):
    left = dict(_CLEAN_LEFT, analyst_output=[f"p-{i}" for i in range(20)])
    right = dict(left, analyst_output=[f"other-{i}" for i in range(20)])
    _run(capsys, [
        "shadow", "compare", "--report-id", "rep-1", "--run-id", "r1",
        "--consumer-id", "chief", "--batch-class", "decision",
        "--scope-json", '{"p": ["x"]}', "--packet-hash", "p1",
        "--expected-triggers-json", '["t1"]',
        "--left-json", json.dumps(left), "--right-json", json.dumps(right),
        "--db", str(store)])
    _run(capsys, [
        "shadow", "accept", "--report-id", "rep-1", "--surface", sc.ANALYST_OUTPUT,
        "--actor", "owner", "--authority", "chief_owner",
        "--reason", "verified", "--db", str(store)])

